# 形態素解析関数 (変更なし)
def tokenize_with_index(text):
    dic_path = Path(unidic_lite.DICDIR)
    tagger = Tagger(f'-d "{dic_path}"')
    tokens = []
    pos = 0
    for word in tagger(text):
        surface = word.surface
        tokens.append({
            "word": surface,
            "start": pos,
            "end": pos + len(surface)
        })
        pos += len(surface)
    return tokens

